-- Biocare secure home-visit status workflow
-- Adds: en route -> arrived -> in service -> completed, notifications and audit log.

alter table public.care_orders
  drop constraint if exists care_orders_status_check;

alter table public.care_orders
  add constraint care_orders_status_check
  check (status in (
    'received','confirmed','assigned','en_route','arrived',
    'sample_collected','processing','review','completed','ready','cancelled'
  ));

create table if not exists public.care_order_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.care_orders(id) on delete cascade,
  status text not null,
  actor_id uuid null references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.care_order_events enable row level security;
revoke all on public.care_order_events from anon, authenticated;

create or replace function public.care_staff_orders_v2()
returns table(
  order_number text,
  service_type text,
  service_name text,
  status text,
  active boolean
)
language sql
security definer
set search_path = ''
as $$
  select
    o.order_number,
    o.service_type,
    o.service_name,
    o.status,
    a.active
  from public.care_visit_assignments a
  join public.care_orders o on o.id=a.order_id
  join public.care_field_staff s on s.user_id=a.staff_id
  where a.staff_id=(select auth.uid())
    and s.active=true
    and a.active=true
    and o.service_type in ('home_lab','doctor','nursing','physio')
    and o.status in ('assigned','en_route','arrived','processing')
  order by a.created_at desc
$$;

create or replace function public.care_staff_set_visit_status(
  p_order_number text,
  p_status text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_order_id uuid;
  v_patient_id uuid;
  v_current text;
  v_expected text;
  v_title text;
  v_body text;
begin
  if v_uid is null then
    raise exception 'Authentication required';
  end if;

  select o.id,o.patient_id,o.status
    into v_order_id,v_patient_id,v_current
  from public.care_orders o
  join public.care_visit_assignments a on a.order_id=o.id
  join public.care_field_staff s on s.user_id=a.staff_id
  where o.order_number=p_order_number
    and a.staff_id=v_uid
    and a.active=true
    and s.active=true
    and o.service_type in ('home_lab','doctor','nursing','physio')
  for update of o;

  if v_order_id is null then
    raise exception 'Visit not assigned';
  end if;

  v_expected := case v_current
    when 'assigned' then 'en_route'
    when 'en_route' then 'arrived'
    when 'arrived' then 'processing'
    when 'processing' then 'completed'
    else null
  end;

  if v_expected is null or p_status <> v_expected then
    raise exception 'Invalid status transition';
  end if;

  update public.care_orders
  set status=p_status,updated_at=now()
  where id=v_order_id;

  insert into public.care_order_events(order_id,status,actor_id)
  values(v_order_id,p_status,v_uid);

  if p_status='en_route' then
    v_title:='فريق الزيارة في الطريق';
    v_body:='فريق الزيارة المنزلية في الطريق لطلبك رقم '||p_order_number||'. يمكنك متابعة الموقع من التطبيق.';
  elsif p_status='arrived' then
    v_title:='وصل فريق الزيارة';
    v_body:='وصل فريق الزيارة المنزلية إلى موقعك للطلب رقم '||p_order_number||'.';
  elsif p_status='processing' then
    v_title:='بدأت الزيارة';
    v_body:='بدأ تنفيذ الزيارة المنزلية للطلب رقم '||p_order_number||'.';
  elsif p_status='completed' then
    v_title:='اكتملت الزيارة';
    v_body:='اكتملت الزيارة المنزلية للطلب رقم '||p_order_number||'. شكرًا لاستخدامك بيوكير.';
  end if;

  insert into public.care_notifications(patient_id,title,body)
  values(v_patient_id,v_title,v_body);

  if p_status='completed' then
    update public.care_visit_assignments
      set active=false
      where order_id=v_order_id and staff_id=v_uid;

    update public.care_team_locations
      set active=false,updated_at=now()
      where order_id=v_order_id;
  end if;

  return p_status;
end;
$$;

revoke all on function public.care_staff_orders_v2() from public, anon;
revoke all on function public.care_staff_set_visit_status(text,text) from public, anon;

grant execute on function public.care_staff_orders_v2() to authenticated;
grant execute on function public.care_staff_set_visit_status(text,text) to authenticated;
